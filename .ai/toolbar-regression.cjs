const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { clickControl } = require('./browser-controls.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve('index.html')).href);
    await page.locator('#modal-help button[data-close]').click();
    assert.equal(await page.locator('#field-toolbar #share-menu').count(), 1);
    assert.equal(await page.locator('#field-toolbar #btn-maze').count(), 1);
    assert.equal(await page.locator('#hud-corn').isVisible(), true);
    assert.equal(await page.locator('#maze-menu').isVisible(), false);
    assert.equal(await page.locator('#panel-play #btn-export-json').count(), 0, 'share options should move out of the sidebar');
    const about = page.locator('#about-developer');
    assert.equal(await about.getAttribute('href'), 'https://appsbydan.com');
    assert.equal(await about.getAttribute('target'), '_blank');
    assert.ok((await about.getAttribute('rel')).includes('noopener'));
    const geometry = await page.evaluate(() => ({ field: document.getElementById('field').getBoundingClientRect().toJSON(), support: document.getElementById('field-support').getBoundingClientRect().toJSON(), sidebar: document.querySelector('.panel').getBoundingClientRect().toJSON() }));
    assert.ok(geometry.support.top >= geometry.field.bottom, 'coffee link belongs below the field');
    assert.ok(geometry.support.left < geometry.sidebar.left, 'coffee link should be in the field column');
    const tractor = await page.evaluate(() => ({ ...window.__cornfield.state().tractor }));
    await page.locator('#share-summary').focus(); await page.keyboard.press('Enter');
    await page.locator('#btn-export-json').focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('u');
    assert.deepEqual(await page.evaluate(() => ({ ...window.__cornfield.state().tractor })), tractor, 'keyboard menu navigation must not control the tractor');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#share-menu').getAttribute('open'), null);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'share-summary');
    await clickControl(page, '#btn-export-json');
    await page.locator('#modal-share').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#share-menu').getAttribute('open'), null);
    await page.locator('#modal-share button[data-close]').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'share-summary', 'closing the modal must restore focus to the visible menu summary');
    await page.locator('#share-summary').click(); await page.locator('#creation-name').click();
    assert.equal(await page.locator('#share-menu').getAttribute('open'), null);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'creation-name', 'outside-click dismissal must retain the clicked focus');
    const png = page.waitForEvent('download'); await clickControl(page, '#btn-png');
    assert.match((await png).suggestedFilename(), /\.png$/);
    await page.locator('#btn-maze').click();
    for (const id of ['hud-time', 'hud-moves', 'hud-corn', 'hud-route']) assert.equal(await page.locator('#' + id).isVisible(), false, 'maze mode should replace top stat chips with tools');
    assert.equal(await page.locator('#maze-summary').isVisible(), true);
    await clickControl(page, '#btn-place-start'); await page.locator('#field').focus(); await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight');
    await clickControl(page, '#btn-place-exit'); await page.locator('#field').focus(); await page.keyboard.press('Enter');
    await clickControl(page, '#mode-run');
    await page.locator('#field').focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight');
    await page.locator('#win').waitFor({ state: 'visible' });
    await page.locator('#win-share').click(); await page.locator('#modal-share').waitFor({ state: 'visible' });
    await page.locator('#modal-share button[data-close]').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'win-share', 'share from victory should retain its own focus origin');
    await page.locator('#win-again').click();
    await page.screenshot({ path: '.ai/previews/final-toolbar-maze.png', fullPage: true });
    await page.locator('#btn-maze').click();
    assert.equal(await page.locator('#hud-corn').isVisible(), true);
    assert.equal(await page.locator('#maze-menu').isVisible(), false);
    await page.screenshot({ path: '.ai/previews/final-toolbar-art.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Toolbar PASS: art/maze border tools, share dropdown exports, keyboard/focus/outside dismissal, victory share, under-field coffee and developer link.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
